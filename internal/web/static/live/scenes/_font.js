// width of text in font pixels (1 pixel gap between glyphs)
export const textWidth = (s) => [...s].reduce((w, ch) => w + (FONT[ch] || FONT[" "])[0].length + 1, -1);

// big draws text with its top-left at cell (c, r); px, py: cells per font pixel.
export function big(g, s, c, r, px, py, color, char = "█") {
  for (const ch of s) {
    const rows = FONT[ch] || FONT[" "];
    for (let fy = 0; fy < 7; fy++) for (let fx = 0; fx < rows[fy].length; fx++) {
      if (rows[fy][fx] !== "1") continue;
      const col = typeof color === "function" ? color(fx, fy) : color;
      for (let a = 0; a < py; a++) for (let b = 0; b < px; b++) g.put(c + fx * px + b, r + fy * py + a, char, col);
    }
    c += (rows[0].length + 1) * px;
  }
}
